"""User account and investor profile."""

from __future__ import annotations

from datetime import date
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, CheckConstraint, Date, Integer, Numeric, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin
from app.models.enums import RiskTolerance

if TYPE_CHECKING:
    from app.models.alert import Alert
    from app.models.goal import Goal
    from app.models.holding import Holding
    from app.models.model_output import ModelOutput
    from app.models.snapshot import PortfolioSnapshot
    from app.models.transaction import Transaction


class User(Base, TimestampMixin):
    """An investor account and the profile that drives personalised analysis."""

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(primary_key=True)
    email: Mapped[str] = mapped_column(String(255), unique=True, index=True, nullable=False)
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)
    full_name: Mapped[str | None] = mapped_column(String(255))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    # --- investor profile ---
    age: Mapped[int | None] = mapped_column(Integer)
    annual_income: Mapped[float | None] = mapped_column(Numeric(16, 2))
    monthly_savings: Mapped[float | None] = mapped_column(Numeric(16, 2))
    risk_tolerance: Mapped[RiskTolerance | None] = mapped_column(String(20))
    investment_horizon_years: Mapped[int | None] = mapped_column(Integer)

    # Marks accounts generated by the synthetic cohort builder, so demo data
    # is never mistaken for a real user in analysis or in the UI.
    is_synthetic: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    synthetic_archetype: Mapped[str | None] = mapped_column(String(50))
    joined_on: Mapped[date | None] = mapped_column(Date)

    holdings: Mapped[list["Holding"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    transactions: Mapped[list["Transaction"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    goals: Mapped[list["Goal"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    snapshots: Mapped[list["PortfolioSnapshot"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    model_outputs: Mapped[list["ModelOutput"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )
    alerts: Mapped[list["Alert"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )

    __table_args__ = (
        CheckConstraint("age IS NULL OR (age BETWEEN 18 AND 100)", name="age_range"),
        CheckConstraint("annual_income IS NULL OR annual_income >= 0", name="income_non_negative"),
        CheckConstraint(
            "monthly_savings IS NULL OR monthly_savings >= 0", name="savings_non_negative"
        ),
        CheckConstraint(
            "investment_horizon_years IS NULL OR investment_horizon_years > 0",
            name="horizon_positive",
        ),
    )

    def __repr__(self) -> str:
        return f"<User {self.id} {self.email}>"
